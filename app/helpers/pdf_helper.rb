# frozen_string_literal: true

# Shared Prawn pieces pulled out of TimesheetsHelper.
# TimesheetsHelper then does `include PdfHelper` and deletes its own copies of these methods.
module PdfHelper
  # Pads previous_text with NBSPs so whatever follows starts at roughly target_width.
  def _dynamic_nbsp(pdf, previous_text, target_width = 550)
    text_width = pdf.width_of(previous_text)
    nbsp_width = pdf.width_of(Prawn::Text::NBSP)
    remaining_width = target_width - text_width
    count = [(remaining_width / nbsp_width).floor, 1].max

    Prawn::Text::NBSP * count
  end

  # Same as before, with target_width added so it works on A4 portrait too (A3 landscape default stays 550).
  def _write_line(pdf:, previous_text:, next_text: '', move_down: 40, target_width: 550)
    ensure_space(pdf:, required_height: 20)
    gap = _dynamic_nbsp(pdf, previous_text, target_width)

    pdf.text("#{previous_text}#{gap}#{next_text}")
    pdf.move_down move_down
  end

  # Running header on every page (note: the option is `style:`, not `Style:`)
  def _add_running_header(pdf:, text:)
    pdf.repeat(:all) do
      pdf.move_cursor_to pdf.bounds.top
      pdf.text text, align: :right, style: :bold, size: 6
    end
  end

  def _add_footer(pdf:) # rubocop:disable Metrics/MethodLength
    pdf.repeat(:all) do
      pdf.bounding_box([pdf.bounds.left, 30], width: pdf.bounds.width) do
        pdf.move_down 5
        pdf.stroke_horizontal_rule
        pdf.move_down 5
        pdf.text(
          "This document was generated by OMIS © Global Health Informatics Institute - #{Time.current.year}",
          size: 6,
          align: :center
        )
      end
    end
  end

  def _add_stamp(pdf:, y: 350, width: nil)
    stamp_width = width || (pdf.bounds.width / 3)
    pdf.repeat(:all) do
      pdf.image(
        'app/assets/images/GHII-stamp.png',
        width: stamp_width,
        at: [pdf.bounds.right - stamp_width, y]
      )
    end
  end

  def ensure_space(pdf:, required_height:)
    footer_zone = 100
    return unless pdf.cursor < footer_zone + required_height

    pdf.start_new_page
    pdf.move_down 10
  end
end
